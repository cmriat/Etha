"""Batch state management for TensorBus.

A batch represents one call to register_tensors(). Multiple batches can exist
for the same pair, each with independent tensors and handlers.
"""

from dataclasses import field, dataclass

import torch
import torch.distributed as dist

from etha.comm.ir import Bucket


@dataclass(kw_only=True)
class BatchState:
    """Runtime state for a single batch of registered tensors, held on the Agent.

    Created per register_tensors() call. Holds live tensors, process-group
    handles, and execution plans (buckets with CUDA work) — in-memory only.

    Key design: buckets are FLATTENED across all pairs in the batch, allowing
    single-pass execution via bucket_comm().
    """

    batch_id: str  # UUID generated by client
    pair_names: list[str]  # Which pairs are involved in this batch
    generation: int = 0  # incremented on each reuse of batch_id; CleanupBatch must match

    # Leader coordination for batch-level operations
    local_leader: int | None = None  # local_ranks[0], set during registration
    local_group: dist.ProcessGroup | None = None  # shared local_group, set during registration
    batch_group: dist.ProcessGroup | None = None  # all ranks in batch (local + remote across all pairs)

    # Data layer: Per-pair organization (for fallback and debugging)
    pair_tensors: dict[str, list[torch.Tensor]] = field(default_factory=dict)
    pair_target_dtypes: dict[str, list[torch.dtype]] = field(default_factory=dict)

    # Execution layer: FLATTENED across all pairs for efficient execution
    send_buckets: list[Bucket] | None = None
    recv_buckets: list[Bucket] | None = None

    # Configuration
    bucket_size: int | None = None

    # --- Dual-endpoint (colocated) state --------------------------------------
    # A dual batch is registered twice on the same agent — once per role. The
    # two registrations merge (never overwrite) into the structures below;
    # chunks/buckets are generated only once both roles are present, because
    # the wire dtype needs both sides and the wire ops live in physical rank
    # space shared by both roles.
    dual: bool = False
    # (pair_name, role) -> that role's registered tensors, in registration order
    pair_role_tensors: dict[tuple[str, str], list[torch.Tensor]] = field(default_factory=dict)
    # (pair_name, role) -> per-tensor dtypes (needed for min-itemsize wire dtype)
    pair_role_dtypes: dict[tuple[str, str], list[torch.dtype]] = field(default_factory=dict)
    # (src_role, dst_role) -> flattened buckets for that direction (chunks
    # accumulated across ALL pairs of the batch, then bucketized once)
    dual_direction_buckets: dict[tuple[str, str], list[Bucket]] = field(default_factory=dict)
    # (src_role, dst_role) -> last executed sync_round for that direction;
    # rounds <= it are acknowledged without re-execution (stale/duplicate)
    dual_direction_done: dict[tuple[str, str], int] = field(default_factory=dict)
    # First requested direction; names are supplied by the clients, not Etha.
    dual_direction: tuple[str, str] | None = None
    # ((src_role, dst_role), sync_round) -> {"roles": {arrived roles},
    # "semaphores": [parked command semaphores]}. A direction-round executes
    # only once both roles' Transfer commands arrived; until then the first
    # command parks here. Cleared by execution or CleanupBatch.
    dual_round_pending: dict[tuple[tuple[str, str], int], dict] = field(default_factory=dict)
    # Role-independent registration layout, shared by both gathers.
    dual_layout_signature: tuple | None = None
    # Semaphores of RegisterTensors commands that returned while the batch was
    # still waiting for its other role; released when the second role completes
    # generation (or by CleanupBatch, so a failed batch cannot hang a client)
    pending_register_semaphores: list[str] = field(default_factory=list)
